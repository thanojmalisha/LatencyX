export function getQualityTier(ping) {
  if (ping <= 40) return { tier: 'S', label: 'Excellent', color: '#00ff88', bgColor: 'rgba(0,255,136,0.15)' };
  if (ping <= 70) return { tier: 'A', label: 'Good', color: '#66ff00', bgColor: 'rgba(102,255,0,0.15)' };
  if (ping <= 100) return { tier: 'B', label: 'Fair', color: '#ffcc00', bgColor: 'rgba(255,204,0,0.15)' };
  if (ping <= 150) return { tier: 'C', label: 'High Latency', color: '#ff6600', bgColor: 'rgba(255,102,0,0.15)' };
  return { tier: 'D', label: 'Poor', color: '#ff2222', bgColor: 'rgba(255,34,34,0.15)' };
}
